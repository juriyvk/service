import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const files=['docs/staging-bootstrap.sql','supabase/migrations/202611120001_crm.sql','supabase/migrations/202611120002_existing_employees.sql'];
const parts=await Promise.all(files.map(f=>readFile(new URL(f,root),'utf8')));
const strip=s=>s.replace(/^begin;\s*$/gm,'').replace(/^commit;\s*$/gm,'').trim();
const smoke=await readFile(new URL('scripts/staging-smoke.sql',root),'utf8');
const result=`-- GENERATED by node scripts/build-staging.mjs. Do not edit by hand.
-- TARGET: https://supabase.com/dashboard/project/wepogbvijpvyvyfzxzeo/sql/new
-- NEW EMPTY STAGING ONLY. Existing employee or CRM tables cause an abort.
-- One atomic transaction: creates schema, tests with synthetic fixtures, removes fixtures.
begin;
do $$ begin
 if to_regnamespace('dvfm') is not null then raise exception 'CRM schema already exists; stop and inspect, do not reinstall'; end if;
end $$;
${parts.map((s,i)=>`\n-- SOURCE: ${files[i]}\n${strip(s)}\n`).join('')}
${smoke}
-- Record the two canonical migrations so a later CLI db push does not replay them.
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations(version text primary key,statements text[],name text);
insert into supabase_migrations.schema_migrations(version,name,statements) values
 ('202611120001','crm',array[]::text[]),('202611120002','existing_employees',array[]::text[]);
commit;
select 'staging_schema_ready' as status,
 (select count(*) from public.employees) as employees,
 (select count(*) from dvfm.tasks) as tasks,
 (select count(*) from dvfm.outbox) as queued_notifications;
`;
const path=new URL('docs/staging-setup.sql',root);
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==result)throw new Error('Run node scripts/build-staging.mjs to regenerate staging SQL');}
else await writeFile(path,result);
